export function buildFirstResultGatewayPrompt(task: string): string {
  const normalized = task.toLowerCase().replace(/ё/g, 'е');
  const isLanding = ['лендинг', 'сайт', 'страниц'].some((token) => normalized.includes(token));
  const isPresentation = ['презент', 'слайд', 'deck', 'дек'].some((token) => normalized.includes(token));
  const isSales = ['скрипт', 'продаж', 'оффер', 'воронк'].some((token) => normalized.includes(token));

  const formatInstruction = isLanding
    ? `Это задача на лендинг. Верни ГОТОВЫЙ текст страницы: сильный первый экран, подзаголовок, CTA, проблема, решение, услуги/выгоды, блок доверия, тарифы, возражения/FAQ и финальная форма заявки. Пиши реальные тексты блоков, а не "нужно написать".`
    : isPresentation
      ? `Это задача на презентацию. Верни ГОТОВОЕ содержание слайдов: название каждого слайда и конкретный текст/тезисы для него. Не описывай, что нужно сделать.`
      : isSales
        ? `Это задача на продажи. Верни ГОТОВЫЙ оффер/скрипт/сообщения, которые можно сразу использовать. Не давай план их подготовки.`
        : `Верни законченный рабочий материал по задаче, который можно сразу использовать.`;

  return `Ты — производственный AI-директор Бизнес-Завода. Твоя задача — не советовать, а производить готовый результат.

ЗАДАЧА ПОЛЬЗОВАТЕЛЯ:
${task}

${formatInstruction}

КРИТИЧЕСКИ ВАЖНО:
- не пересказывай ТЗ;
- не начинай с "план", "что делать первым", "я бы сделал";
- не пиши рекомендации вместо результата;
- не используй Markdown-звёздочки ** или служебные пометки;
- заголовки пиши отдельной строкой;
- текст должен быть на русском, конкретным, сильным и без канцелярщины;
- если данных не хватает, сделай разумные допущения и всё равно выдай цельный первый вариант.

Верни только готовый материал.`;
}

export function buildFirstResultFallbackPlan(task: string): string {
  const focus = task.trim() || 'вашей задачи';

  return [
    'Начнём с простого.',
    'Сфокусируйтесь на одном понятном шаге на эту неделю.',
    '',
    `1. Сформулировать цель по задаче: «${focus}».`,
    '2. Выбрать один быстрый результат, который можно проверить за 1–2 дня.',
    '3. Решить, кто в команде ведёт первый этап.',
    '4. Сделать первый шаг и зафиксировать одну метрику.',
    '5. Вернуться завтра и скорректировать план по факту.',
    '',
    'Когда будете готовы — сохраните это и продолжите со мной.',
  ].join('\n');
}

export function buildWorkspaceTaskFallback(task: string, projectName: string): string {
  const focus = task.trim();
  const project = projectName.trim() || 'вашего проекта';

  return [
    `Я набросала первый шаг для ${project}.`,
    'Сейчас важнее ясности, чем скорости.',
    '',
    `Задача: ${focus}`,
    '',
    '1. Уточнить цель на ближайшие 7 дней.',
    '2. Выделить один результат, по которому будет виден прогресс.',
    '3. Сделать черновик и проверить гипотезу.',
    '4. Зафиксировать одну метрику успеха.',
    '5. Решить, что сделать следующим шагом.',
    '',
    'Можем продолжить вместе, когда будете готовы.',
  ].join('\n');
}

export function resolveFirstPlanContent(
  task: string,
  gatewayContent: string | null | undefined,
): { content: string; usedFallback: boolean } {
  const trimmed = gatewayContent?.trim();

  if (trimmed) {
    return { content: trimmed, usedFallback: false };
  }

  return {
    content: buildFirstResultFallbackPlan(task),
    usedFallback: true,
  };
}
