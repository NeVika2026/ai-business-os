export function resolveFirstPlanContent(
  task: string,
  gatewayContent: string | null | undefined,
): { content: string; usedFallback: boolean } {
  const showcaseDraft = buildShowcaseSafeDraft(task);
  if (showcaseDraft) {
    return { content: showcaseDraft, usedFallback: false };
  }

  const trimmed = gatewayContent?.trim();

  if (trimmed) {
    if (isClarificationOnlyFirstResult(trimmed)) {
      return { content: buildGuardedFirstDraft(task), usedFallback: false };
    }

    return { content: trimmed, usedFallback: false };
  }

  return {
    content: buildFirstResultFallbackPlan(task),
    usedFallback: true,
  };
}
